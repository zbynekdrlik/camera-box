"""issue 1457 (owner 21.10.2026): the phones hear the cutter as loud as the camboxes.

"sluchatka v camboxoch pocuju dobre nahlas strihaca ale pripojeny cez web interkom-pp.newlevel.media pocuju
potichu strihaca". Read live the same day: intercom.strih-pp.toml carried cutters -> cameras +6 dB (added
14.10.2026) while cutters -> phones stayed 0 dB. Owner rulings the same evening:
  * "a vsetko ma byt rovnako aj v pp aj snv lebo ronvaky je setup" -- one rule for both venues;
  * "probram nemen tak nechaj to je spravne" -- the program feeds keep their level;
  * "cize len strihac do kamier oprav co je v pp pridane +6db" -- only the +6 dB goes.
So every talkback point (between the cameras, the cutters and the phones) is unity on PP and SNV, and
the program into the cutters' ears keeps its -8 dB (PP) / -8 and -10 dB (SNV). The full table of gain
points read that evening is on the ticket (comment 6320886718).
"""

import tomllib
from pathlib import Path

REPO = Path(__file__).resolve().parent.parent.parent
PP_TOMLS = [REPO / "intercom" / "intercom.strih-pp.toml", REPO / "intercom" / "intercom.stream-pp.toml"]
# owner 21.10.2026: "a vsetko ma byt rovnako aj v pp aj snv lebo ronvaky je setup"
ALL_TOMLS = PP_TOMLS + [REPO / "intercom" / "intercom.strih-snv.toml"]


# --- the routing files ---------------------------------------------------------------------------------

def _program_refs(m):
    return {p["name"] for p in m["participant"] if p["role"] == "program_ref"}


def test_every_talkback_point_is_unity_on_both_venues():
    """Every point between the talkers (cameras, cutters, phones) is unity, on PP and SNV alike. The
    program feeds keep their level (owner 21.10.2026: "probram nemen tak nechaj to je spravne")."""
    for f in ALL_TOMLS:
        m = tomllib.loads(f.read_text())
        prog = _program_refs(m)
        off = [(p["src"], p["dst"], p["out_ch"], p["gain_db"]) for p in m["point"]
               if p["src"] not in prog and p.get("gain_db", 0.0) != 0.0]
        assert not off, "%s: %s" % (f.name, off)


def test_the_program_level_into_the_cutters_ears_is_kept():
    """owner 21.10.2026: "probram nemen tak nechaj to je spravne" -- lv1 -> cutters stays 8 dB down on
    PP (the SNV lv1/fohabl -> cutters points keep their VB-Matrix -8/-10 dB, generated by the converter)."""
    m = tomllib.loads(PP_TOMLS[0].read_text())
    to_cut = sorted((p["in_ch"], p["out_ch"], p.get("gain_db", 0.0)) for p in m["point"]
                    if p["src"] == "lv1" and p["dst"] == "cutters")
    assert to_cut == [(1, 1, -8.0), (2, 2, -8.0)], to_cut
    snv = tomllib.loads(ALL_TOMLS[-1].read_text())
    assert {p.get("gain_db", 0.0) for p in snv["point"] if p["src"] in ("lv1", "fohabl") and p["dst"] == "cutters"} \
        <= {-8.0, -10.0}


def test_the_cutter_reaches_the_cameras_and_the_phones_at_the_same_level():
    m = tomllib.loads(PP_TOMLS[0].read_text())
    gains = {(p["dst"], p.get("gain_db", 0.0)) for p in m["point"] if p["src"] == "cutters"}
    assert {g for _, g in gains} == {0.0}, gains
    assert {"cam1", "cam4", "cam6", "cam7", "phones"} <= {d for d, _ in gains}
