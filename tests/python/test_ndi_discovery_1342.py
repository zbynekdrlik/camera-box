class ReceiverConfig(unittest.TestCase):
    def test_config_json_is_receiver_only(self):
        r = _lib("ndi_discovery_config_json")
        self.assertEqual(r.returncode, 0, r.stderr)
        doc = json.loads(r.stdout)
        self.assertEqual(doc, {"ndi": {"networks": {"ips": _pinned()}}})
        self.assertNotIn("discovery", r.stdout)
        self.assertTrue(r.stdout.endswith("}\n"))
        self.assertFalse(r.stdout.startswith(chr(0xFEFF)), "never a BOM")

    def test_config_json_takes_an_explicit_list(self):
        r = _lib('ndi_discovery_config_json "10.0.0.1,10.0.0.2"')
        self.assertEqual(json.loads(r.stdout)["ndi"]["networks"]["ips"], "10.0.0.1,10.0.0.2")

    def test_parsers(self):
        text = '{"ndi": {"networks": {"ips": "10.77.9.61, 10.77.9.62", "discovery": "10.77.9.200"}}}'
        r = _lib(f"T='{text}'; ndi_discovery_config_ips \"$T\"; ndi_discovery_config_servers \"$T\"")
        self.assertEqual(r.stdout.splitlines(), ["10.77.9.61, 10.77.9.62", RETIRED_SERVER_IP])

    def test_verdict_ok_on_the_rendered_config(self):
        r = _lib('ndi_discovery_config_verdict "$(ndi_discovery_config_json)"')
        self.assertEqual(r.stdout.strip(), "ok", r.stdout + r.stderr)

    def test_verdict_accepts_extras_spaces_and_any_order(self):
        ips = list(reversed(_expected_pinned_ips())) + ["10.77.9.201"]
        text = json.dumps({"ndi": {"networks": {"ips": ", ".join(ips)}}})
        r = _lib(f"ndi_discovery_config_verdict '{text}'")
        self.assertEqual(r.stdout.strip(), "ok", r.stdout)

    def test_verdict_fails_each_facet(self):
        pinned = _pinned()
        short = ",".join(_expected_pinned_ips()[1:])
        cases = {
            "": "missing",
            '{"ndi":{"networks":{"ips":"' + pinned + '"}}': "JSON",
            json.dumps({"ndi": {"networks": {"ips": pinned, "discovery": RETIRED_SERVER_IP}}}): "discovery",
            json.dumps({"ndi": {"networks": {"ips": short}}}): _expected_pinned_ips()[0],
            json.dumps({"ndi": {"networks": {"ips": ""}}}): "ips",
        }
        for text, facet in cases.items():
            r = _lib(f"ndi_discovery_config_verdict '{text}'")
            self.assertEqual(r.returncode, 0, r.stderr)
            self.assertTrue(r.stdout.startswith("FAIL:"), f"{text!r} must FAIL, got {r.stdout!r}")
            self.assertIn(facet, r.stdout, f"{text!r} verdict must name {facet!r}: {r.stdout!r}")

    def test_verdict_grades_against_an_explicit_required_list(self):
        text = json.dumps({"ndi": {"networks": {"ips": "10.0.0.1"}}})
        self.assertEqual(_lib(f"ndi_discovery_config_verdict '{text}' 10.0.0.1").stdout.strip(), "ok")
        self.assertTrue(_lib(f"ndi_discovery_config_verdict '{text}' 10.0.0.1,10.0.0.2").stdout.startswith("FAIL:"))

    def test_dropin_points_the_service_at_the_system_config_dir(self):
        r = _lib('ndi_discovery_dropin_content; printf "DIR=%s\\n" "$(ndi_discovery_dropin_config_dir "$(ndi_discovery_dropin_content)")"')
        self.assertEqual(r.returncode, 0, r.stderr)
        self.assertRegex(r.stdout, r"(?m)^\[Service\]$")
        self.assertRegex(r.stdout, r"(?m)^Environment=NDI_CONFIG_DIR=/etc/ndi$")
        self.assertIn("DIR=/etc/ndi", r.stdout)
        self.assertNotIn("Discovery Server", r.stdout)

    def test_dropin_parser_empty_when_absent(self):
        r = _lib("ndi_discovery_dropin_config_dir ''; echo \"rc=$?\"")
        self.assertEqual(r.stdout.strip(), "rc=0")


class Writer(unittest.TestCase):
    def test_writes_the_rendered_file_idempotently(self):
        with tempfile.TemporaryDirectory() as tmp:
            target = os.path.join(tmp, "a", ".ndi")
            for _ in range(2):
                r = _lib(f'ndi_discovery_write_config "{target}" "$(ndi_discovery_sender_ips pinned)"')
                self.assertEqual(r.returncode, 0, r.stderr)
            path = os.path.join(target, "ndi-config.v1.json")
            self.assertEqual(_read(path), _lib("ndi_discovery_config_json").stdout)
            self.assertEqual(oct(os.stat(path).st_mode & 0o777), "0o644")
            self.assertEqual(os.listdir(target), ["ndi-config.v1.json"], "no temp file / backup left behind")

    def test_merge_keeps_other_keys_sets_ips_and_drops_a_discovery_server(self):
        with tempfile.TemporaryDirectory() as tmp:
            path = os.path.join(tmp, "ndi-config.v1.json")
            with open(path, "w") as fh:
                fh.write('{"ndi": {"groups": {"recv": "Public"}, "networks": {"ips": "10.77.8.51", "discovery": "10.77.9.200"}}, "other": 1}')
            r = _lib(f'ndi_discovery_write_config "{tmp}" "10.0.0.1,10.0.0.2"')
            self.assertEqual(r.returncode, 0, r.stderr)
            doc = json.loads(_read(path))
            self.assertEqual(doc["ndi"]["groups"], {"recv": "Public"})
            self.assertEqual(doc["other"], 1)
            self.assertEqual(doc["ndi"]["networks"], {"ips": "10.0.0.1,10.0.0.2"},
                             "a managed box never keeps a discovery server (it would silence its senders' mDNS)")

    def test_unparseable_existing_config_is_backed_up_then_replaced(self):
        with tempfile.TemporaryDirectory() as tmp:
            path = os.path.join(tmp, "ndi-config.v1.json")
            with open(path, "w") as fh:
                fh.write("{not json")
            r = _lib(f'ndi_discovery_write_config "{tmp}" "10.0.0.1"')
            self.assertEqual(r.returncode, 0, r.stderr)
            self.assertEqual(_read(path), _lib('ndi_discovery_config_json "10.0.0.1"').stdout)
            baks = [f for f in os.listdir(tmp) if f.startswith("ndi-config.v1.json.bak-")]
            self.assertEqual(len(baks), 1, os.listdir(tmp))
            self.assertEqual(_read(os.path.join(tmp, baks[0])), "{not json")

    def test_an_empty_list_is_refused(self):
        with tempfile.TemporaryDirectory() as tmp:
            r = _lib(f'ndi_discovery_write_config "{tmp}" ""; echo "rc=$?"')
            self.assertNotIn("rc=0", r.stdout)
            self.assertEqual(os.listdir(tmp), [])

    def test_fails_loud_on_an_unwritable_dir(self):
        r = _lib('ndi_discovery_write_config "/proc/ndi-discovery-cannot-exist" "10.0.0.1"; echo "rc=$?"')
        self.assertNotIn("rc=0", r.stdout)


