def _read(path: str) -> str:
    with open(path, encoding="utf-8") as fh:
        return fh.read()


def _bash(script: str, env=None) -> subprocess.CompletedProcess:
    e = dict(os.environ)
    for k in _SCRUB:
        e.pop(k, None)
    if env:
        e.update(env)
    return subprocess.run(
        ["bash", "-c", script], capture_output=True, text=True, timeout=30, cwd=REPO, env=e
    )


def _lib(body: str, env=None) -> subprocess.CompletedProcess:
    return _bash(f'set -uo pipefail\n. "{LIB}"\n{body}', env=env)


def _live_flow(path: str, guard: str) -> str:
    text = _read(path)
    pos = text.find(guard)
    assert pos >= 0, f"source-guard marker {guard!r} missing from {path}"
    return text[pos:]


def _strip_comments(text: str) -> str:
    return "\n".join(l for l in text.splitlines() if not l.lstrip().startswith("#"))


def _expected_pinned_ips() -> list:
    """The pinned list, derived INDEPENDENTLY of the lib from the two fleet sources of truth: every
    `camN) CAMERA_IP=<ip>` arm of camera_resolve, in order, then every IPv4 host of the obs-fleet
    ndi-sender facet (retired rows excluded by obs_fleet_boxes)."""
    cams = re.findall(r"(?m)^\s*cam(\d+)\) CAMERA_IP=([0-9.]+);", _read(CAMERA_SET))
    ips = [ip for _, ip in sorted(cams, key=lambda c: int(c[0]))]
    r = _bash(f'. "{OBS_FLEET}"; obs_fleet_boxes ndi-sender')
    assert r.returncode == 0, r.stderr
    for pair in r.stdout.split():
        host = pair.split("|", 1)[1]
        if re.fullmatch(r"\d+\.\d+\.\d+\.\d+", host) and host not in ips:
            ips.append(host)
    return ips


def _pinned() -> str:
    return ",".join(_expected_pinned_ips())


