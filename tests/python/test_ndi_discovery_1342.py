"""Tier-0 tests for issue 1342: the camboxes publish ONE NDI output, and every managed RECEIVER
queries every managed SENDER by IP, in addition to mDNS.

Three parts, all pure-bash / file-content checks (no cargo, no rig):

1. The unconsumed issue-792 `CAMn (30p)` blend stream is GONE (part 1, unchanged).
   - There is no `src/publish_30p.rs` and no wiring for it.
   - setup-device.sh REMOVES a leftover `publish-30p.conf`.
   - verify-device.sh has no `(z)` check.
2. Part 2, the revised main design: a RECEIVER-ONLY `ndi-config.v1.json`.
   - `networks.ips` is GENERATED by one pure function in `scripts/lib/ndi-discovery.sh` from the fleet
     sources of truth: `scripts/camera-set.sh` (every camera `camera_resolve` knows) and
     `scripts/lib/obs-fleet.sh` (the `ndi-sender` facet: strih-lx, stream, resolume).
   - The config carries NO `networks.discovery`. The NDI SDK (`Processing.NDI.Find.h`, `p_extra_ips`)
     queries the listed IPs IN ADDITION to mDNS, and senders never read the list. So senders keep
     announcing over mDNS, and stock TVs, guest laptops and the avahi port-map audit keep working.
   - There is no gate: receiver config is safe to ship.
   - The writers are setup-device STEP 7, setup-strih step 4b and the Windows `.ps1`. The graders are
     verify-device `(an)` and verify-strih item 34, which use the SAME generator.
3. The Discovery-Server model of part 1 is dead code and is removed: the dev1 server unit, the
   `networks.discovery` writers, the rollout gates and the server list.
"""

