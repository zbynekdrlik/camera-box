//! #186 — the ONE trustworthy, binary zero-loss check.
//!
//! Replaces the muddled per-hop loss metrics (`dropped` / `phantom` / `gap` /
//! painter-tick beat / `real_gap`) with a SINGLE definitive check that a
//! non-engineer can trust:
//!
//!   Each rendered frame carries a DIGITAL monotonic burn id — a per-node counter
//!   generated in our own code (cam1-capture burn, strih burn, stream burn). Every
//!   node forwards its burn into the stream program output, so the SINGLE stream
//!   recording carries all three burn-id sequences.
//!
//!   THE CHECK: is each node's burn-id sequence, as decoded from the STREAM
//!   recording, CONTIGUOUS — every consecutive integer from first..=last present,
//!   no gap?
//!
//!   - Contiguous ⇒ ZERO loss for that hop: every frame the node rendered reached
//!     the recording.
//!   - A missing id ⇒ ONE candidate dropped frame, classified definitively by
//!     viewing the pixels at that position in the recording:
//!       * the frame is PRESENT but its burn QR is unreadable (the frame and its
//!         OTHER QRs decode) ⇒ a BURN-READABILITY defect to FIX, NOT a frame drop
//!         (the burn is digitally generated by our own code, so it MUST be made
//!         readable — bigger / crisper). Reported, never silently excluded.
//!       * the frame is genuinely ABSENT (no frame at that grid slot, black /
//!         garbage) ⇒ a REAL dropped frame.
//!
//! No percentages, no jargon. The output is the single binary:
//!   "ZERO loss: all burn-id sequences contiguous (N frames, M seconds)"
//!   OR "NOT zero: <list> — each id: REAL DROP (pixel) or BURN-UNREADABLE (pixel)".
//!
//! This module holds the PURE contiguity check (`burn_contiguity`,
//! [`NodeContiguity`]) — fully unit-tested with synthetic burn-id sequences. The
//! pixel classification of each missing id is the I/O glue in the
//! `recording-verdict` binary (it re-decodes neighboring recorded frames), kept out
//! of this pure module so the trustworthy logic is independently provable.

use serde::Serialize;

/// The contiguity verdict for ONE node's burn-id sequence (decoded from the stream
/// recording). Contiguous (`missing_ids` empty) ⇒ ZERO loss for that node's
/// delivery into the recording.
#[derive(Debug, Clone, PartialEq, Eq, Serialize)]
pub struct NodeContiguity {
    /// Node label, e.g. `"cam1"`, `"strih"`, `"stream"`.
    pub node: String,
    /// First burn id seen (the start of the analyzed span). `None` ⇒ no burn at all.
    pub first_id: Option<u32>,
    /// Last burn id seen (the end of the analyzed span). `None` ⇒ no burn at all.
    pub last_id: Option<u32>,
    /// How many DISTINCT burn ids were decoded.
    pub present_count: u32,
    /// How many ids the contiguous span `first..=last` should contain.
    pub expected_count: u32,
    /// The exact ids missing from `first..=last`, sorted ascending. Empty ⇒ contiguous.
    /// Each entry is ONE candidate dropped frame to be classified by pixel.
    pub missing_ids: Vec<u32>,
}

impl NodeContiguity {
    /// ZERO loss for this node ⇔ the burn-id sequence is contiguous (no missing id).
    /// A node that rendered NO burn (`first_id == None`) is NOT a pass — there is
    /// nothing to prove zero on, which must never read as success.
    pub fn is_contiguous(&self) -> bool {
        self.first_id.is_some() && self.missing_ids.is_empty()
    }
}

/// THE trustworthy check, pure: given the burn ids one node rendered that reached
/// the stream recording (the [`crate::probe::recording_latency::burn_ids_in`]
/// output for that node's run_id), report whether the sequence is contiguous and,
/// if not, EVERY missing id.
///
/// Duplicates are collapsed (the 60→30 sampling beat puts one render id on several
/// recorded frames — the SAME integer, never loss). Order is irrelevant (a set
/// membership test over `first..=last`). The span is `min(ids)..=max(ids)`; an id
/// missing inside that span is a candidate dropped frame.
///
/// An empty input ⇒ `first_id == None` ⇒ NOT contiguous (nothing proven). A
/// single-id input is trivially contiguous (span of one, nothing can be missing).
pub fn burn_contiguity(node: &str, ids: &[u32]) -> NodeContiguity {
    use std::collections::BTreeSet;
    let present: BTreeSet<u32> = ids.iter().copied().collect();
    let first_id = present.iter().next().copied();
    let last_id = present.iter().next_back().copied();
    let (first, last) = match (first_id, last_id) {
        (Some(f), Some(l)) => (f, l),
        _ => {
            return NodeContiguity {
                node: node.to_string(),
                first_id: None,
                last_id: None,
                present_count: 0,
                expected_count: 0,
                missing_ids: Vec::new(),
            };
        }
    };
    // expected = last - first + 1 (the size of the contiguous integer span). Saturating math
    // so a degenerate full-u32-range span (unreachable for run-bounded CRC-validated burn ids,
    // but defensive) can never panic on a debug-build overflow.
    let expected_count = (last - first).saturating_add(1);
    let present_count = present.len() as u32;
    let missing_ids: Vec<u32> = (first..=last).filter(|id| !present.contains(id)).collect();
    NodeContiguity {
        node: node.to_string(),
        first_id: Some(first),
        last_id: Some(last),
        present_count,
        expected_count,
        missing_ids,
    }
}

/// One IN-WINDOW recorded delivered frame's burn status for a node (#198).
///
/// The stream recording is decoded frame-by-frame; each entry here is ONE recorded
/// DELIVERED frame (it carries cam2's optical QR ⇒ a real emitted output frame reached
/// the recording) that falls WITHIN the signal window (after the leading-discard of
/// pre-/post-signal frames). `burn_id` is `Some(id)` when this node's burn QR decoded on
/// that frame, `None` when the delivered frame carried no readable burn for this node.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub struct RecordedBurnFrame {
    /// 0-based recorded frame_index (for slot location / pixel proof).
    pub frame_index: u64,
    /// This node's burn id decoded on the frame, or `None` if the burn was not readable.
    pub burn_id: Option<u32>,
}

/// How a node's burn `frame_id` advances — the #198 distinction that decides whether a
/// forward integer skip between two consecutive recorded (emitted) frames is loss.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum BurnRate {
    /// cam1: the burn id increments ONCE PER EMITTED frame (src/main.rs — after the genlock
    /// decimation gate, right before the NDI send). So consecutive recorded frames MUST carry
    /// consecutive integers; a forward gap (id jumps by >1) means cam1 emitted a frame that
    /// never reached the recording ⇒ a REAL drop. The in-window id sequence must be a
    /// contiguous integer run.
    PerEmittedFrame,
    /// strih/stream: the burn id is the DistroAV burn filter's `f->frame_id++`, bumped in the
    /// OBS `video_render` callback — once per RENDER/COMPOSITE TICK, which fires FASTER than
    /// the emitted/recorded output rate (vendor/distroav/src/ndi-burn-filter.cpp:261). So a
    /// forward gap between consecutive recorded frames is the EXPECTED un-emitted render ticks
    /// and is NOT loss; only a delivered frame carrying NO burn (or a backward jump) is.
    PerRenderTick,
}

/// Why a missing burn id is missing (#198) — determined from the in-window walk itself, so
/// the REAL-DROP vs BURN-UNREADABLE distinction is decided by the rate/structure, not lost.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum InWindowMissingKind {
    /// A frame the node EMITTED that never reached the recording: a per-emit (cam1) forward
    /// integer gap (an emitted-frame id absent from the recorded sequence), or a backward
    /// jump (reorder). The node's own frame is genuinely gone ⇒ a REAL drop.
    RealDrop,
    /// A DELIVERED frame (cam2's optical QR present at this slot) that carried NO readable node
    /// burn — the frame reached the recording but the burn QR did not decode ⇒ a
    /// BURN-READABILITY defect to FIX, not an absent frame.
    BurnUnreadable,
}

/// One missing-frame slot the in-window check found: the (synthetic-or-real) burn `id` that
/// was absent, the recorded `frame_index` whose pixels prove the cause, and the `kind` decided
/// by the walk (#198). The verdict binary pairs onto THIS authoritative list (single source of
/// truth) and extracts the pixel proof at `frame_index` — it no longer recomputes the walk.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub struct MissingSlot {
    pub id: u32,
    pub frame_index: u64,
    pub kind: InWindowMissingKind,
}

/// The in-window contiguity verdict + the recorded slot for each missing id (#198).
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct InWindowContiguity {
    pub contiguity: NodeContiguity,
    /// One per `contiguity.missing_ids` entry, SAME order, SAME length — the recorded frame to
    /// view for that missing id. The verdict binary zips these together; the lengths are
    /// guaranteed equal by construction (both produced in this one walk).
    pub missing_slots: Vec<MissingSlot>,
}

/// The in-window contiguity check with `expected_step == 1` (no decimation): every render tick /
/// emitted frame is one recorded frame, so per-render forward gaps are unconditionally ignored —
/// today's behavior, unchanged. For a DECIMATED hop (the strih burn read from the lower-fps stream
/// recording, where the 60 fps strih render is captured at 30 → ids step by 2 by design) call
/// [`burn_contiguity_in_window_with_step`] with the decimation factor.
pub fn burn_contiguity_in_window(
    node: &str,
    frames: &[RecordedBurnFrame],
    rate: BurnRate,
) -> InWindowContiguity {
    burn_contiguity_in_window_with_step(node, frames, rate, 1)
}

/// THE in-window contiguity check (#198), correct for BOTH burn-counter rates.
///
/// ## Why the old integer-range check over-counted strih/stream by ~3x
///
/// [`burn_contiguity`] (above) treats the burn `frame_id` as a per-EMITTED-frame counter:
/// it builds the span `min(ids)..=max(ids)` and calls every absent integer "missing". That is
/// only valid for **cam1** ([`BurnRate::PerEmittedFrame`]), whose burn id increments once per
/// EMITTED frame. For **strih/stream** ([`BurnRate::PerRenderTick`]) the burn id is bumped per
/// OBS render tick, which fires FASTER than the emitted/recorded rate. So strih's counter ran
/// to ~28676 while only ~9000 frames were emitted into the ~300 s recording: every render tick
/// that produced no distinct emitted frame is an integer the recording never carries, and the
/// old check flagged ALL of them as "missing" (the 18056 false report in #198). Restricting to
/// a window does NOT fix that alone — the render-tick skips are INTERIOR to the window; the
/// rate is the dominant cause (#198 point 2).
///
/// ## The correct measure (rate-aware)
///
/// A recording frame is one EMITTED output frame. The check walks the in-window DELIVERED
/// frames (each carries cam2's optical QR ⇒ a frame DID reach the recording at that instant):
///
/// - a delivered frame carrying NO readable node burn (`burn_id == None`) is ALWAYS a candidate
///   drop (the node's frame for that instant was lost OR its burn was unreadable) — for BOTH
///   rates;
/// - for [`BurnRate::PerRenderTick`] (strih/stream): a BACKWARD jump (id < the previous present
///   id) is a reorder/corruption fault (a free-running render counter only advances); a FORWARD
///   gap is the EXPECTED un-emitted render ticks and is NOT loss.
/// - for [`BurnRate::PerEmittedFrame`] (cam1): real drops are computed SET-WISE, not by the
///   recorded-frame walk (#216). A cam1 emitted-frame integer is GENUINELY LOST iff it is absent
///   from the whole present-set within `min(present)..=max(present)`. This is ORDER-INDEPENDENT,
///   so an id the softened recording delivers out of order (a one-frame-late 60→30 straddle) can
///   NEITHER manufacture a phantom drop (it is present elsewhere) NOR be counted twice, and a
///   backward jump to a present id is correctly benign — while a genuinely-absent integer is
///   still caught (it loudly widens the missing set). Each BURN-UNREADABLE (`None`) frame already
///   consumed one emitted id (the #133 distinction), so the absent count is reduced by the
///   unreadable-frame count before any are charged as drops. Each truly-absent id is listed ONCE.
///
/// Out-of-window frames are excluded entirely (the caller passes only in-window delivered
/// frames via [`RecordedBurnFrame`]), so the pre-/post-signal ids that inflated the range can
/// no longer be counted as missing — the #198 point-1 ask.
///
/// `frames` MUST be the in-window DELIVERED recorded frames in recorded order. The returned
/// [`NodeContiguity`] uses `first_id`/`last_id` = the first/last burn id in RECORDED order;
/// `expected_count` = the number of in-window delivered frames; `present_count` =
/// `expected_count − (DELIVERED non-present frames)` = delivered frames that carried a readable
/// burn (a `None` frame and a per-render backward-jump frame are the delivered non-present ones).
///
/// RECONCILIATION (read carefully — it differs by rate):
/// - `present_count + (None frames + per-render backward jumps) == expected_count`, ALWAYS. These
///   are the delivered frames.
/// - cam1 (per-emit) GENUINELY-absent ids are EXTRA missing_slots that are NOT delivered frames
///   (no recorded frame carried them — they were lost), so they are appended to `missing_ids`
///   ON TOP of the delivered reconciliation. Therefore `present_count + missing_ids.len()` is
///   NOT an invariant for cam1 (a pure reorder/duplicate window has `present + 0 missing == expected`,
///   and a lost id adds to missing_ids without subtracting from present). For per-render, every
///   missing_id IS a delivered non-present frame, so there `present + missing == expected` holds.
///
/// `missing_ids` is paired 1:1 with [`InWindowContiguity::missing_slots`] (same order/length) so
/// the pixel classifier views the exact recorded frame; the order is the BurnUnreadable/per-render
/// faults in walk order, then the cam1 genuinely-absent ids ascending (no consumer assumes a sort).
/// Consecutive `None` frames get DISTINCT synthetic ids so a deduping consumer cannot undercount.
/// An empty / all-`None` window ⇒ `first_id == None` ⇒ NOT a pass (nothing proven).
///
/// ## Decimation-aware step (`expected_step`) — the mixed 60/30 topology (#11)
///
/// For a [`BurnRate::PerRenderTick`] node read from a recording captured at a LOWER fps than the
/// node's render rate — the strih burn (rendered at 60 on the strih box) read from the 30 fps
/// STREAM recording — consecutive recorded frames carry render-tick ids that step by the by-design
/// DECIMATION factor `expected_step` (60/30 = 2: the stream's genlock FIFO keeps every other strih
/// frame). A forward gap **== `expected_step`** IS that decimation and is NOT loss; a forward gap
/// **> `expected_step`** means one or more emitted output frames never reached the recording — the
/// excess `gap / expected_step − 1` (INTEGER division, so genlock beat jitter of
/// `expected_step ± 1` charges 0) is appended as [`InWindowMissingKind::RealDrop`]. This is the
/// load-bearing no-masking fix: without it the per-render forward gap is UNCONDITIONALLY ignored,
/// so a real loss in the decimated hop (a gap of 4 where 2 is by-design) reads as a false ZERO.
/// The no-masking guarantee is EXACT at the rig's `expected_step == 2` (the only un-charged gap is
/// 3 = genuine beat jitter); for a hypothetical `expected_step >= 3` (non-default fps) a single
/// drop landing in `step+1 ..= 2·step−1` is charged 0 by the integer division — sustained/multi-slot
/// loss is still always caught. The rig runs step=2, so this blind spot is not reachable in prod.
///
/// The excess check is GATED on `expected_step >= 2` (a configured decimation hop). With
/// `expected_step == 1` the per-render forward gap stays UNCONDITIONALLY ignored exactly as before
/// — so the strih burn in a 60-in-60 strih recording, the stream burn recorded by its own 30 fps
/// OBS (emit rate == capture rate ⇒ step 1), and the cam render-tick semantics are all unchanged
/// (the [`burn_contiguity_in_window`] back-compat wrapper passes `1`).
///
/// #571 — cam1/cam3/cam4 ([`BurnRate::PerEmittedFrame`]) on a DECIMATED hop (`expected_step >= 2`
/// — the Topology-v2 cam(60fps)->strih(30fps) hop, where strih's 30fps recording samples only
/// ~half of the camera's emitted ids): FORWARD GAPS in the captured id sequence are BY-DESIGN
/// decimation and are NOT charged as real drops AT ALL. No gap-size math can separate them from
/// loss — the real beat (run 554307) is bursts of delta-1 then a jump of ~7 (delta histogram
/// {0: 2, 1: 9256, 6: 34, 7: 1767, 8: 45}, mean 1.998), so an observed-cadence step reads the
/// dominant delta 1 and charges every jump (11087 phantom drops on a chain where strih's OWN
/// 911002 burn was fully contiguous), while a fixed step-2 grid masks genuine step-1 drops. The
/// correct discriminator is WHETHER THE HOP IS CONFIGURED DECIMATED (`expected_step`, from the
/// fps ratio), not the gap size. Genuine loss on the decimated hop is caught by the signals that
/// REMAIN IN FORCE: a delivered frame with NO readable burn (`None` → BurnUnreadable, still fails
/// the gate), the downstream node's OWN per-render burn (strih 911002), the cam2→cam1 OPTICAL
/// tick (a 1:1, non-decimated read), and the frozen-camera gate (#365). On a 1:1 hop
/// (`expected_step == 1`) forward gaps ARE charged — the exact pre-#571 strict first..=last scan,
/// unchanged (the #356/#208 never-mask invariant). For PerRenderTick (strih/stream)
/// `expected_step` is used directly (the decimated-render branch above).
///
/// The decimation-excess RealDrops are absent frames BETWEEN two delivered frames (like the cam1
/// genuinely-absent ids), NOT delivered frames, so they are EXTRA entries in `missing_ids` and
/// `present_count + missing_ids.len()` is NOT an invariant for a decimated per-render node either.
pub fn burn_contiguity_in_window_with_step(
    node: &str,
    frames: &[RecordedBurnFrame],
    rate: BurnRate,
    expected_step: i64,
) -> InWindowContiguity {
    burn_contiguity_in_window_with_step_and_schedule(node, frames, rate, expected_step, None)
}

/// #708 — identical computation to [`burn_contiguity_in_window_with_step`], but additionally
/// told which `--switch-schedule` window (if any) each entry of `frames` belongs to, via
/// `window_of[i]` aligned 1:1 with `frames[i]` (`None` ⇒ unknown: no schedule was supplied, the
/// frame carried no gen_ts anchor, or it fell in a transition guard / outside every window).
///
/// ## Why strih needed this (the bug this closes)
///
/// strih's OWN 911002 render-tick burn is attached to EVERY raw `NDI camN` input (six
/// INDEPENDENT DistroAV filter instances — one per source — so whichever gets cut to PROGRAM
/// already carries a burn; `recording-e2e.sh`'s `BURN_TARGETS`), and each instance's counter
/// free-runs for the WHOLE recording regardless of whether that source is currently on air (the
/// Multiview projector keeps every raw input rendering — a `#365` hard precondition). So the six
/// counters' numeric ranges are NOT one global monotone sequence: they routinely OVERLAP
/// (live-proven, #708: one run's cam5 range was `66709..=67840`, cam6's `66934..=68067` — cam6's
/// own counter reached a value cam5's counter ALSO covers, at a completely different wall-clock
/// time). [`burn_contiguity_in_window_with_step`]'s per-render backward-jump check (below) — built
/// for a genuine SINGLE free-running counter, where a backward jump can only mean reorder/
/// corruption — misreads the EXPECTED counter-instance change at a program switch as that same
/// fault: every one of a run's flagged strih `real_drop` ids was found, byte-for-byte, both in
/// strih's own recording AND (independently) downstream in the stream recording — genuinely never
/// lost anywhere, on two independent CI runs (issue #708 evidence).
///
/// The fix: when the caller CONFIRMS (via `window_of`) that the previous present frame and the
/// current one sit in two DIFFERENT `--switch-schedule` windows, the backward-jump / decimation-
/// excess checks for THIS ONE comparison are suppressed — it is the EXPECTED per-source counter
/// discontinuity, not a fault. An UNKNOWN window on either side (no schedule, no anchor, inside a
/// guard) NEVER suppresses — it falls back to the strict pre-#708 behavior, so this can only ever
/// NARROW the flagged set on a CONFIRMED boundary, never accidentally mask a genuine in-window
/// fault (a backward jump within ONE window — the SAME free-running counter instance, which can
/// never legitimately go backward — still FAILS exactly as before).
pub fn burn_contiguity_in_window_with_step_and_schedule(
    node: &str,
    frames: &[RecordedBurnFrame],
    rate: BurnRate,
    expected_step: i64,
    window_of: Option<&[Option<usize>]>,
) -> InWindowContiguity {
    let present_ids: Vec<u32> = frames.iter().filter_map(|f| f.burn_id).collect();
    let first_id = present_ids.first().copied();
    let last_id = present_ids.last().copied();
    // Expected = the number of in-window DELIVERED frames: each one is an emitted output
    // frame that MUST carry this node's burn. (Not the integer span — that span is the
    // free-running render-tick range for strih/stream, not the emitted-frame count.)
    let expected_count = frames.len() as u32;

    if first_id.is_none() {
        return InWindowContiguity {
            contiguity: NodeContiguity {
                node: node.to_string(),
                first_id: None,
                last_id: None,
                present_count: 0,
                expected_count,
                missing_ids: Vec::new(),
            },
            missing_slots: Vec::new(),
        };
    }

    // Walk the in-window delivered frames in order, recording every missing slot with the id
    // it should have carried, the recorded frame to view, and WHY it is missing. `next_synth`
    // is a strictly-monotone cursor for the synthetic ids of `None` slots so consecutive drops
    // ALWAYS get DISTINCT ids — a deduping consumer can never collapse two real drops into one
    // (#198 review #1). It is seeded above the integer range so it can never collide with a
    // real present/gap id (#198 review #3).
    let max_present = present_ids.iter().copied().max().unwrap_or(0);
    let mut next_synth = max_present.saturating_add(1);
    let mut alloc_synth = || {
        let v = next_synth;
        next_synth = next_synth.saturating_add(1);
        v
    };

    // #216 — the GLOBAL present-set: every burn id decoded ANYWHERE in this window. cam1's
    // burn is a strictly-monotone per-EMITTED-frame counter, so an emitted id can only be
    // absent from this set if its frame genuinely never reached the recording (a real drop).
    // An id that IS in the set but arrives slightly OUT OF ORDER in recorded-frame order — a
    // one-frame-late 60→30 straddle / duplicate through the softened stream recording (#133,
    // #196) — is a MEASUREMENT reorder, NOT a lost frame, and must not be counted. The
    // per-emit forward-gap and backward-jump branches below cross-check against this set so a
    // reordered-but-present id is never manufactured into a phantom REAL DROP. (This is what
    // the 30-min proof exposed: 235 cam1 "real_drops" while present_ids covered the FULL
    // integer span — every emitted integer WAS present, nothing lost.)
    let present_set: std::collections::BTreeSet<u32> = present_ids.iter().copied().collect();

    let mut missing_slots: Vec<MissingSlot> = Vec::new();
    let mut prev_present: Option<u32> = None;
    // Count delivered (in-window) frames that are NOT a clean "present": a `None` frame (no
    // burn) and a per-render backward-jump frame (carries a burn but out of order). Each is ONE
    // delivered frame, so it subtracts from present_count → present + these == expected
    // (#198 review #2). A per-emit GENUINELY-absent id (computed set-wise after the walk) is NOT
    // a delivered frame, so it does NOT subtract — it is an EXTRA real drop in missing_ids only.
    let mut non_present_delivered: u32 = 0;
    // For per-emit (cam1) the real-drop detection is SET-based (below the walk), not order-based,
    // so reorder + unreadable interactions can no longer manufacture or double-count drops. Map
    // each present id → the FIRST recorded frame_index it appeared on, so a set-absent id can be
    // paired to the recorded slot of the next present id ABOVE it (the frame after the gap — the
    // most useful pixel-proof slot). For per-render (strih/stream) the walk below still does the
    // order-based backward-jump check (their free-running counter has no per-emit ordering
    // guarantee to lean on, so an out-of-order id IS a fault).
    use std::collections::{BTreeMap, BTreeSet};
    let mut id_to_frame: BTreeMap<u32, u64> = BTreeMap::new();
    // #216 review — track the SPECIFIC emitted id each BURN-UNREADABLE (`None`) frame consumed,
    // by its POSITION in the monotone walk (NOT a blind "skip N lowest"). For cam1 a None frame
    // sits right after the last present id `prev`, so the id it would have carried is the next
    // contiguous integer: `prev + (count of Nones since prev)`. Recording those exact ids and
    // EXCLUDING them from the genuine-drop set means: a trailing/out-of-span None can no longer
    // cancel an in-span real drop (review finding #1), and the wrong absent id can no longer be
    // dropped from the front (review finding #2). Each None accounts for ITS own id, nothing else.
    let mut unreadable_consumed: BTreeSet<u32> = BTreeSet::new();
    let mut nones_since_prev: u32 = 0;
    // #708 — the schedule-window index of the previous PRESENT frame. Mirrors `prev_present`'s
    // own carry-across-`None`-frames semantics (only updated on a `Some` arm), so a run of
    // BURN-UNREADABLE frames spanning a window boundary never resets it prematurely. `None`
    // whenever `window_of` is absent (the overwhelming majority of callers — see the
    // `burn_contiguity_in_window_with_step` wrapper) or a specific frame's window is unknown.
    let mut prev_present_window: Option<usize> = None;
    for (i, f) in frames.iter().enumerate() {
        match f.burn_id {
            Some(id) => {
                id_to_frame.entry(id).or_insert(f.frame_index);
                let cur_window = window_of.and_then(|w| w.get(i).copied().flatten());
                // #708 — a schedule-window boundary crossing is CONFIRMED only when BOTH sides'
                // windows are known and differ; any unknown side falls back to the strict
                // pre-#708 behavior (see the function doc — never silently masks a genuine fault).
                let crossed_window_boundary = matches!(
                    (prev_present_window, cur_window),
                    (Some(pw), Some(cw)) if pw != cw
                );
                if let Some(prev) = prev_present {
                    // Per-render (strih/stream): a monotone free-running counter can ONLY advance,
                    // so a backward jump is a reorder/corruption fault — ALWAYS counted. (cam1
                    // uses the set-based check below instead; a cam1 backward jump to a present id
                    // is just the softened recording delivering it late, never a fault.)
                    // #708 EXCEPTION — a backward jump landing EXACTLY at a CONFIRMED
                    // `--switch-schedule` window boundary is the EXPECTED per-source free-running
                    // counter discontinuity (strih's 911002 burn runs one independent counter per
                    // raw camera input — see the function doc), not a lost frame. Suppressed ONLY
                    // for this one boundary comparison; a backward jump WITHIN one window (the
                    // SAME counter instance, which can never legitimately go backward) still FAILS.
                    // #708 RED (test-first): the suppression is NOT wired up yet in this commit
                    // — only the `window_of`/`crossed_window_boundary` THREADING is added, so the
                    // new tests below can call the real function signature and observe them FAIL.
                    // The next commit adds `&& !crossed_window_boundary` here to make them pass.
                    let _ = crossed_window_boundary;
                    if id < prev && matches!(rate, BurnRate::PerRenderTick) {
                        non_present_delivered = non_present_delivered.saturating_add(1);
                        missing_slots.push(MissingSlot {
                            id,
                            frame_index: f.frame_index,
                            kind: InWindowMissingKind::RealDrop,
                        });
                    }
                    // A per-render FORWARD gap: for a NON-decimated hop (expected_step == 1) it is
                    // the expected un-emitted render ticks and is NOT loss (today's behavior,
                    // unchanged). For a DECIMATED hop (expected_step >= 2 — the 60fps strih burn
                    // read from the 30fps stream recording, ids step by ~2 by design), a gap of
                    // EXACTLY expected_step is the decimation; a gap LARGER than that means one or
                    // more emitted output frames never reached the recording — charge the excess
                    // as REAL DROPs. The gap spans `gap/expected_step` decimation slots; ONE is the
                    // current present frame, and `nones_since_prev` of them were DELIVERED frames
                    // whose burn was UNREADABLE (each already charged BURN-UNREADABLE in the None
                    // arm — those slots reached the recording, they are NOT lost). So the genuinely
                    // absent slots are `excess = gap/expected_step − 1 − nones_since_prev` (integer
                    // division, so genlock beat jitter of expected_step ± 1 charges 0; crediting the
                    // Nones stops a gap that straddles an unreadable burn from manufacturing a
                    // phantom REAL DROP for the exact slot the None already accounts for — the
                    // #133/#226 RealDrop-vs-BurnUnreadable honesty). These are absent frames BETWEEN
                    // two delivered frames (not delivered frames themselves), so — like cam1's
                    // set-based genuinely-absent ids — they are EXTRA missing_slots that do NOT
                    // subtract from present_count. The missing ids `prev + k·expected_step` lie
                    // strictly inside (prev, id) ⇒ below max_present ⇒ never collide with a
                    // synthetic None id (seeded above max_present) or a present id.
                    // (cam1's per-emit forward gap is handled set-wise below — neither acts here.)
                    // #708 RED (test-first): same as the backward-jump branch above — the
                    // suppression is added in the next (GREEN) commit.
                    if matches!(rate, BurnRate::PerRenderTick) && expected_step >= 2 && id > prev {
                        let gap = id as i64 - prev as i64;
                        let excess = gap / expected_step - 1 - i64::from(nones_since_prev);
                        if excess > 0 {
                            for k in 1..=excess {
                                let missing_id = prev as i64 + k * expected_step;
                                missing_slots.push(MissingSlot {
                                    id: missing_id as u32,
                                    frame_index: f.frame_index,
                                    kind: InWindowMissingKind::RealDrop,
                                });
                            }
                        }
                    }
                }
                prev_present = Some(id);
                prev_present_window = cur_window;
                nones_since_prev = 0;
            }
            None => {
                // A delivered frame with no readable burn ⇒ the frame reached the recording but
                // the burn QR did not decode ⇒ BURN-UNREADABLE (both rates). A fresh synthetic
                // id keeps consecutive Nones distinct and cannot collide with a real id. This
                // delivered frame is NOT a clean present.
                non_present_delivered = non_present_delivered.saturating_add(1);
                nones_since_prev = nones_since_prev.saturating_add(1);
                // The specific emitted id this None consumed: the next contiguous id after the last
                // present (prev + 1, + 1 per consecutive None). When there is no prev present yet
                // (a leading None), it has no in-sequence id to charge — it consumes nothing from
                // the absent set (it cannot mask an in-span drop). #133 per-emit accounting.
                // #571: only the 1:1 hop's candidate generation below consumes this set; on a
                // DECIMATED hop (expected_step >= 2) no forward-gap candidates exist at all, so
                // the set is simply unused there (harmless).
                if matches!(rate, BurnRate::PerEmittedFrame) {
                    if let Some(prev) = prev_present {
                        unreadable_consumed.insert(prev.saturating_add(nones_since_prev));
                    }
                }
                missing_slots.push(MissingSlot {
                    id: alloc_synth(),
                    frame_index: f.frame_index,
                    kind: InWindowMissingKind::BurnUnreadable,
                });
            }
        }
    }

    // #216 — cam1 (PerEmittedFrame) REAL DROPS, computed SET-WISE (order-independent), so a
    // reorder (an id delivered out of order by the softened recording) can NEITHER manufacture a
    // phantom drop NOR double-count, and a backward-jump-to-a-present-id is correctly benign. A
    // cam1 emitted-frame integer is GENUINELY LOST iff it is absent from the whole present-set
    // within the observed span `min(present)..=max(present)` AND it was NOT the id a BURN-UNREADABLE
    // frame consumed (those ids are undecodable, not frames that never arrived — the #133
    // distinction). Each genuinely-lost id is listed ONCE, paired to the recorded slot of the next
    // present id above it for the pixel proof.
    // #571: the forward-gap candidate generation runs ONLY on a 1:1 hop (`expected_step <= 1`).
    // On a DECIMATED hop (`expected_step >= 2` — the Topology-v2 cam(60fps)->strih(30fps) hop) a
    // forward gap is BY-DESIGN decimation and produces NO candidates at all: the real beat (run
    // 554307: delta-1 bursts + ~7 jumps) makes every gap-size heuristic wrong in one direction or
    // the other (charge-everything or mask-real-drops), so the forward-gap signal is simply
    // INVALID there. Genuine decimated-hop loss is still caught by the None arm above
    // (BurnUnreadable), the downstream node's own per-render burn, and the optical tick — see
    // the function docstring.
    if matches!(rate, BurnRate::PerEmittedFrame) && expected_step <= 1 {
        // The span is MIN..=MAX of the present ids (NOT the recorded first/last, which can be out
        // of order through the softened recording — e.g. a corrupt low id makes first > last).
        let span = present_set
            .iter()
            .next()
            .copied()
            .zip(present_set.iter().next_back().copied());
        if let Some((lo, hi)) = span {
            let last_frame = frames.last().map(|f| f.frame_index).unwrap_or(0);
            // #226 — a blurred-but-PRESENT cam1 burn must be BURN-UNREADABLE, never REAL DROP,
            // but ONLY when a delivered frame demonstrably fell in the gap. The proof signature
            // (run 1924001): present_count == expected_count (NO `None` frame) yet ids are absent
            // from the present-set on a periodic beat. CRC32 (Payload::decode) makes a
            // wrong-but-valid id impossible, so the blurred burn on a DELIVERED frame re-decoded
            // to an already-seen (CRC-valid) DUPLICATE of a neighbor id — leaving the id it SHOULD
            // have carried absent from the set, yet a delivered frame DID sit at that slot.
            //
            // CRUCIAL discriminator (the deep-review catch): the per-emit chain ALSO legitimately
            // puts the SAME id on several recorded frames via the 60→30 sampling beat (a benign
            // oversample, the DOMINANT duplicate source — see the docstring above). A benign
            // oversample sits AT an already-present id's recorded position (adjacent to its own
            // id); a #226 misdecode sits STRICTLY INSIDE a gap between two DIFFERENT present ids.
            // So we must NOT count total duplicates (that masks genuine drops that merely coexist
            // with oversamples) — we count, PER GAP, only the recorded frames that physically lie
            // BETWEEN the gap's bounding present ids in RECORDED order. Each such interstitial
            // frame is a delivered frame that fell in the gap ⇒ one absent id in that gap is
            // BURN-UNREADABLE; the rest of the gap had no delivered frame ⇒ genuine REAL DROP.
            //
            // Walk the recorded frames in order, tracking the count of interstitial (duplicate /
            // out-of-gap) frames seen since the last STRICTLY-INCREASING present id. When the next
            // present id jumps forward by >1 (opening a gap), that accumulated interstitial count
            // is the number of delivered-but-misdecoded frames that fell in THIS gap. (Frames are
            // already in recorded order; present_set membership + a monotone high-water cursor
            // identify a forward step vs an in-gap duplicate.)
            let mut interstitial_since_step: u32 = 0;
            let mut hi_water: Option<u32> = None;
            // gap_lo (exclusive) -> interstitial-frame count that fell inside that gap.
            let mut gap_unreadable: BTreeMap<u32, u32> = BTreeMap::new();
            // Ids decoded SO FAR in the walk. Only a frame whose id was ALREADY seen (a genuine
            // DUPLICATE — the misdecode/oversample fingerprint) counts as an interstitial
            // delivered frame. A present-set member arriving LATE / out of order (the #216 reorder
            // — a single occurrence, just not in ascending recorded position) is accounted for by
            // its own presence in the set, so it must NOT credit a gap's budget (deep-review #2:
            // otherwise a genuine drop in a LATER gap is mislabeled BurnUnreadable).
            let mut seen: BTreeSet<u32> = BTreeSet::new();
            for f in frames {
                // `None` frames are handled by unreadable_consumed, not here.
                let Some(id) = f.burn_id else { continue };
                let is_duplicate = !seen.insert(id);
                match hi_water {
                    None => {
                        hi_water = Some(id);
                        interstitial_since_step = 0;
                    }
                    Some(prev_hi) => {
                        if id > prev_hi.saturating_add(1) {
                            // A forward gap opened (prev_hi+1 ..= id-1 absent). The DUPLICATE frames
                            // seen since prev_hi (a misdecode re-stamping a neighbor id) are
                            // delivered frames that fell in this gap.
                            if interstitial_since_step > 0 {
                                gap_unreadable.insert(prev_hi, interstitial_since_step);
                            }
                            hi_water = Some(id);
                            interstitial_since_step = 0;
                        } else if id > prev_hi {
                            // Contiguous forward step (id == prev_hi+1): no gap; reset.
                            hi_water = Some(id);
                            interstitial_since_step = 0;
                        } else if is_duplicate {
                            // id <= prev_hi AND already seen: a genuine DUPLICATE (misdecode /
                            // oversample) — an interstitial delivered frame. It MAY be a misdecode
                            // covering a gap that opens later; accumulate it. A late-arriving FIRST
                            // occurrence of a present id (a reorder) is NOT a duplicate, so it does
                            // not inflate the budget (deep-review #2).
                            interstitial_since_step = interstitial_since_step.saturating_add(1);
                        }
                    }
                }
            }
            // For each absent id, the gap it belongs to is keyed by the largest present id strictly
            // below it. Spend that gap's interstitial budget (lowest absent id first) as
            // BURN-UNREADABLE; the remaining absent ids in the gap are genuine REAL DROPs.
            let mut gap_budget_used: BTreeMap<u32, u32> = BTreeMap::new();
            for missing in (lo..=hi)
                .filter(|id| !present_set.contains(id))
                .filter(|id| !unreadable_consumed.contains(id))
            {
                let frame_index = id_to_frame
                    .range((missing.saturating_add(1))..)
                    .next()
                    .map(|(_, &fi)| fi)
                    .unwrap_or(last_frame);
                // The gap key = the present id immediately below this absent id. This absent id is
                // BURN-UNREADABLE iff its gap still has an unspent interstitial-frame budget (a
                // delivered frame fell in the gap); otherwise it is a genuine REAL DROP.
                let gap_lo = present_set.range(..missing).next_back().copied();
                let has_delivered_frame_in_gap = gap_lo.is_some_and(|g| {
                    let budget = gap_unreadable.get(&g).copied().unwrap_or(0);
                    let used = gap_budget_used.get(&g).copied().unwrap_or(0);
                    used < budget
                });
                let kind = if has_delivered_frame_in_gap {
                    let g = gap_lo.expect("gap_lo is Some when budget check passed");
                    *gap_budget_used.entry(g).or_insert(0) += 1;
                    InWindowMissingKind::BurnUnreadable
                } else {
                    InWindowMissingKind::RealDrop
                };
                missing_slots.push(MissingSlot {
                    id: missing,
                    frame_index,
                    kind,
                });
            }
        }
    }

    let missing_ids: Vec<u32> = missing_slots.iter().map(|s| s.id).collect();
    // present_count = delivered frames that ARE a clean present (carry a burn, in order). So
    // present + non_present_delivered == expected_count exactly (#198 review #2). Forward-gap
    // synthetic misses are NOT delivered frames and are excluded from this reconciliation.
    let present_count = expected_count.saturating_sub(non_present_delivered);

    InWindowContiguity {
        contiguity: NodeContiguity {
            node: node.to_string(),
            first_id,
            last_id,
            present_count,
            expected_count,
            missing_ids,
        },
        missing_slots,
    }
}

