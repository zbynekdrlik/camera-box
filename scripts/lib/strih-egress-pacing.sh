#!/usr/bin/env bash
# airuleset:script-ok source-only library (never executed directly) -- sourced by strih-provision.sh for
# setup-strih.sh step 11b and verify-strih.sh item 16. Like every sibling in scripts/lib/ it must NOT set
# -euo pipefail: sourcing runs it in the CALLER's shell.
#
# scripts/lib/strih-egress-pacing.sh -- issue 1553: the strih / stream box's NDI + JPEG XS SENDER pacing,
# made permanent (the strih-box twin of scripts/lib/cambox-egress-pacing.sh).
#
# Why: strih-pp's 10 GbE rig NIC sends the program / multiview bursts at line rate to receivers on slower
# switch ports (stream-pp 2.5G, grading-pp 1G); the MikroTik egress queue of the slower port tail-dropped
# the microbursts (measured live 25.11.2026). A hand-applied `mq` root + one `fq maxrate 900mbit
# flow_limit 4000 limit 20000` per tx queue made the switch drops 0, and a reboot lost it. `fq` paces per
# FLOW, so PTP / NTP and the intercom are their own flows, never queued behind a video frame.
#
# The tree (design issuecomment-7172341290, Approach 1), every step a `replace` (idempotent: re-run on an
# unchanged tree keeps the same qdisc handles, measured in a netns on a 7.0 kernel):
#   more than one tx queue -> `root handle 1: mq` + one fq per class 1:<queue in HEX> (tc reads the minor
#     as hex: a decimal 1:10..1:16 loop names queue 16 and fails on 1:11.., leaving queues 10-15 unpaced);
#   one tx queue           -> a root fq (mq refuses a single-queue device: "Operation not supported").
#
# Pieces:
#   * the box fact STRIH_EGRESS_PACING_RATE (`none` | <N>mbit | <N>gbit), validated by strih-box-facts.sh;
#   * THIS lib = the ONE declaration of the fq limits + the pure renderers / verdicts;
#   * the GENERATED boot script ${STRIH_EGRESS_PACING_SERVICE} (rig NIC + rate baked in at setup time), run
#     by systemd/strih-egress-pacing.service (oneshot, after network-online, restarts on failure);
#   * setup-strih step 11b: strih_egress_pacing_install (write-if-changed, enable, a live run of the same
#     `replace` script only when the live tree is not the declared one);
#   * verify-strih item 16: strih_egress_pacing_grade_report (reads `tc -j qdisc show dev <nic>`).
# Seams (tests): STRIH_EGRESS_PACING_ROOT (prefix of /usr/local + /etc), STRIH_EGRESS_PACING_SYS (/sys),
# STRIH_EGRESS_PACING_IPADDR (`ip -o -4 addr show` text), tc / systemctl on PATH.
# Tests: tests/python/test_strih_egress_pacing_1553.py.

STRIH_EGRESS_PACING_FLOW_LIMIT="4000"
STRIH_EGRESS_PACING_LIMIT="20000"
STRIH_EGRESS_PACING_SERVICE="strih-egress-pacing"
# Boot retry for a rig NIC that appears late (a USB adapter): an attempt COUNT, never a wall-clock deadline
# (the rig's dsync date master can step the date while a box boots).
STRIH_EGRESS_PACING_RETRY_ATTEMPTS=30
STRIH_EGRESS_PACING_RETRY_SLEEP_S=2
STRIH_EGRESS_PACING_MARKER="GENERATED by scripts/lib/strih-egress-pacing.sh (camera-box issue 1553)"

strih_egress_pacing_script_path() { printf '%s/usr/local/sbin/%s\n' "${STRIH_EGRESS_PACING_ROOT:-}" "$STRIH_EGRESS_PACING_SERVICE"; }
strih_egress_pacing_unit_path() { printf '%s/etc/systemd/system/%s.service\n' "${STRIH_EGRESS_PACING_ROOT:-}" "$STRIH_EGRESS_PACING_SERVICE"; }

# strih_egress_pacing_rate -> the box fact STRIH_EGRESS_PACING_RATE.
strih_egress_pacing_rate() { strih_box_fact STRIH_EGRESS_PACING_RATE; }

# strih_egress_pacing_rate_ok RATE -> 0 iff `none` or <N>mbit / <N>gbit (N 1..999999, no leading zero).
# The digit sets are spelled out: a bracket range follows the locale (issue 1302).
strih_egress_pacing_rate_ok() {
  local LC_ALL=C v="${1-}" d='0123456789'
  [ "$v" = none ] && return 0
  [[ "$v" =~ ^[123456789][${d}]{0,5}(mbit|gbit)$ ]]
}

# strih_egress_pacing_rate_bytes RATE -> the rate in BYTES per second (what `tc -j` prints for fq maxrate:
# 900mbit = 112500000), or nothing (rc 1) when RATE is not a declared rate.
strih_egress_pacing_rate_bytes() {
  local v="${1-}" n
  strih_egress_pacing_rate_ok "$v" && [ "$v" != none ] || return 1
  n="${v%?bit}"
  case "$v" in
    *mbit) echo $((10#$n * 1000000 / 8)) ;;
    *gbit) echo $((10#$n * 1000000000 / 8)) ;;
  esac
}

# strih_egress_pacing_nic_ok NIC -> 0 iff NIC is an interface name that is safe to bake into a script.
strih_egress_pacing_nic_ok() {
  local LC_ALL=C v="${1-}" lower='abcdefghijklmnopqrstuvwxyz' upper='ABCDEFGHIJKLMNOPQRSTUVWXYZ' digit='0123456789'
  [[ "$v" =~ ^[${lower}${upper}${digit}][${lower}${upper}${digit}._-]{0,14}$ ]]
}

# strih_egress_pacing_script_text NIC RATE -> the full boot script (rc 1, nothing printed, on a bad NIC or
# rate). Exit 0 once applied; 1 = the NIC never appeared (the unit restarts for another round); 2 = a tc
# step failed (never retried: it fails the same way again).
strih_egress_pacing_script_text() {
  local nic="${1-}" rate="${2-}"
  strih_egress_pacing_nic_ok "$nic" || return 1
  strih_egress_pacing_rate_bytes "$rate" >/dev/null || return 1
  cat <<EOF
#!/bin/bash
# ${STRIH_EGRESS_PACING_SERVICE} boot script -- ${STRIH_EGRESS_PACING_MARKER}
# and written by setup-strih.sh step 11b; do not edit it on the box, re-run setup-strih.sh.
# Paces the rig NIC's sender egress: fq maxrate ${rate} per flow on every tx queue, so a burst never
# overruns a slower receiver's switch port.
set -euo pipefail
PATH="\$PATH:/usr/sbin:/sbin"
nic=${nic}
rate=${rate}
sys="\${STRIH_EGRESS_PACING_SYS:-/sys}"
sleep_s="\${STRIH_EGRESS_PACING_RETRY_SLEEP_S:-${STRIH_EGRESS_PACING_RETRY_SLEEP_S}}"
n=0
while [ ! -d "\$sys/class/net/\$nic" ]; do
  n=\$((n + 1))
  if [ "\$n" -ge ${STRIH_EGRESS_PACING_RETRY_ATTEMPTS} ]; then
    echo "${STRIH_EGRESS_PACING_SERVICE}: FAILED -- the rig NIC \$nic is not present after \$n attempts, its egress is UNPACED (issue 1553)" >&2
    exit 1
  fi
  [ "\$n" -ne 1 ] || echo "${STRIH_EGRESS_PACING_SERVICE}: the rig NIC \$nic is not present yet -- waiting (issue 1553)" >&2
  sleep "\$sleep_s"
done
q=0
for d in "\$sys/class/net/\$nic/queues"/tx-*; do
  [ ! -d "\$d" ] || q=\$((q + 1))
done
[ "\$q" -ge 1 ] || q=1
fail_tc() { echo "${STRIH_EGRESS_PACING_SERVICE}: tc \$1 on \$nic FAILED -- its egress may be UNPACED (issue 1553)" >&2; exit 2; }
if [ "\$q" -gt 1 ]; then
  tc qdisc replace dev "\$nic" root handle 1: mq || fail_tc "root mq"
  i=1
  while [ "\$i" -le "\$q" ]; do
    cls="\$(printf '1:%x' "\$i")"
    tc qdisc replace dev "\$nic" parent "\$cls" fq maxrate "\$rate" flow_limit ${STRIH_EGRESS_PACING_FLOW_LIMIT} limit ${STRIH_EGRESS_PACING_LIMIT} || fail_tc "fq under \$cls"
    i=\$((i + 1))
  done
else
  tc qdisc replace dev "\$nic" root fq maxrate "\$rate" flow_limit ${STRIH_EGRESS_PACING_FLOW_LIMIT} limit ${STRIH_EGRESS_PACING_LIMIT} || fail_tc "root fq"
fi
echo "${STRIH_EGRESS_PACING_SERVICE}: dev \$nic paced: fq maxrate \$rate flow_limit ${STRIH_EGRESS_PACING_FLOW_LIMIT} limit ${STRIH_EGRESS_PACING_LIMIT} on \$q tx queue(s) (issue 1553)"
EOF
}

# strih_egress_pacing_unit_text -> systemd/strih-egress-pacing.service (byte-parity test).
strih_egress_pacing_unit_text() {
  cat <<EOF
[Unit]
# camera-box: pace the rig NIC's sender egress at boot (issue 1553). The strih / stream box sends NDI and
# JPEG XS bursts at line rate to receivers on slower switch ports, whose egress queue tail-drops them; an
# fq per tx queue with a per-flow maxrate spreads each burst. ExecStart runs the script setup-strih.sh
# GENERATES from scripts/lib/strih-egress-pacing.sh (the rig NIC + the box fact STRIH_EGRESS_PACING_RATE).
# Installed + enabled by setup-strih step 11b; verify-strih item 16 grades the live tree.
Description=camera-box: pace the rig NIC egress (fq maxrate per tx queue, issue 1553)
Documentation=https://github.com/zbynekdrlik/camera-box/issues/1553
After=network-online.target
Wants=network-online.target
StartLimitIntervalSec=0

[Service]
Type=oneshot
RemainAfterExit=yes
ExecStart=/usr/local/sbin/${STRIH_EGRESS_PACING_SERVICE}
TimeoutStartSec=120
Restart=on-failure
RestartSec=30
# A failed tc step (exit 2) fails the same way on every retry: never loop on it.
RestartPreventExitStatus=2

[Install]
WantedBy=multi-user.target
EOF
}

# strih_egress_pacing_tree_verdict RATE QUEUES JSON -> ONE line `OK <detail>` / `DRIFT <detail>` /
# `UNKNOWN <detail>` for `tc -j qdisc show dev <nic>`. QUEUES = the NIC's tx queue count. OK = (QUEUES > 1)
# a root mq with handle 1: and exactly one fq under every class 1:1..1:<QUEUES hex>, or (QUEUES = 1) a
# root fq; every fq with maxrate = RATE (bytes/s in JSON), flow_limit and limit = the declaration. DRIFT
# names every fault. Always returns 0.
strih_egress_pacing_tree_verdict() {
  local rate="${1-}" queues="${2-}" json="${3-}" want
  want="$(strih_egress_pacing_rate_bytes "$rate")" || { echo "UNKNOWN '${rate}' is not a declared rate"; return 0; }
  [[ "$queues" =~ ^[0123456789]+$ ]] && [ "$queues" -ge 1 ] || { echo "UNKNOWN the tx queue count '${queues}' is not readable"; return 0; }
  python3 - "$want" "$queues" "$STRIH_EGRESS_PACING_FLOW_LIMIT" "$STRIH_EGRESS_PACING_LIMIT" "$rate" "$json" <<'PY' || echo "UNKNOWN the qdisc tree could not be graded"
import json, sys
want, queues, flow, limit, rate, text = int(sys.argv[1]), int(sys.argv[2]), int(sys.argv[3]), int(sys.argv[4]), sys.argv[5], sys.argv[6]
try:
    tree = json.loads(text)
    assert isinstance(tree, list)
except Exception:
    print("UNKNOWN `tc -j qdisc show` gave no JSON list (is tc installed?)")
    sys.exit(0)
faults = []
def grade_fq(q, where):
    o = q.get("options") or {}
    if o.get("maxrate") != want:
        got = o.get("maxrate")
        faults.append("%s fq maxrate %s (want %s = %d bytes/s)" % (where, "none" if got is None else "%s bytes/s" % got, rate, want))
    if o.get("flow_limit") != flow:
        faults.append("%s fq flow_limit %s (want %d)" % (where, o.get("flow_limit"), flow))
    if o.get("limit") != limit:
        faults.append("%s fq limit %s (want %d)" % (where, o.get("limit"), limit))
roots = [q for q in tree if q.get("root")]
root = roots[0] if roots else {}
if queues > 1:
    if root.get("kind") != "mq" or root.get("handle") != "1:":
        print("DRIFT the root is %s %s, not mq 1: -- the rig NIC egress is UNPACED" % (root.get("kind", "nothing"), root.get("handle", "")))
        sys.exit(0)
    kids = {}
    for q in tree:
        p = q.get("parent", "")
        if p.startswith("1:"):
            kids.setdefault(p, []).append(q)
    for i in range(1, queues + 1):
        cls = "1:%x" % i
        got = kids.pop(cls, [])
        if not got or got[0].get("kind") != "fq":
            faults.append("%s has %s, not fq -- tx queue %d is UNPACED" % (cls, got[0].get("kind") if got else "nothing", i))
        else:
            grade_fq(got[0], cls)
    for cls in sorted(kids):
        faults.append("an extra qdisc under %s (the NIC has %d tx queues)" % (cls, queues))
    shape = "mq 1: + fq on %d tx queues" % queues
else:
    if root.get("kind") != "fq":
        print("DRIFT the root is %s, not fq -- the rig NIC egress is UNPACED" % root.get("kind", "nothing"))
        sys.exit(0)
    grade_fq(root, "root")
    shape = "root fq (1 tx queue)"
if faults:
    print("DRIFT " + "; ".join(faults))
else:
    print("OK %s, maxrate %s flow_limit %d limit %d" % (shape, rate, flow, limit))
PY
  return 0
}

# strih_egress_pacing_queues SYS NIC -> the NIC's tx queue count from SYS/class/net/NIC/queues/tx-*.
strih_egress_pacing_queues() {
  local sys="${1:?sys required}" nic="${2:?nic required}" d q=0
  for d in "${sys}/class/net/${nic}/queues"/tx-*; do [ ! -d "$d" ] || q=$((q + 1)); done
  echo "$q"
}

# strih_egress_pacing_nic -> the rig NIC (the ONE rule, strih_lx_rig_nic), or rc 1 + its reason on stderr.
strih_egress_pacing_nic() {
  strih_lx_rig_nic "${STRIH_EGRESS_PACING_SYS:-/sys}" "${STRIH_EGRESS_PACING_IPADDR-$(ip -o -4 addr show 2>/dev/null || true)}" "$(strih_lx_ip)"
}

# _strih_egress_pacing_put DEST MODE TEXT -> 0 = unchanged, 10 = written (temp + rename), 1 = failed.
_strih_egress_pacing_put() {
  local dest="$1" mode="$2" text="$3" tmp
  if [ -f "$dest" ] && [ ! -L "$dest" ] && [ "$(stat -c %a "$dest" 2>/dev/null)" = "${mode#0}" ] && cmp -s "$dest" <(printf '%s\n' "$text"); then
    return 0
  fi
  mkdir -p "${dest%/*}" || return 1
  tmp="$(mktemp "${dest%/*}/.${dest##*/}.XXXXXX")" || return 1
  if ! { printf '%s\n' "$text" > "$tmp" && chmod "$mode" "$tmp" && { [ "$(id -u)" != 0 ] || chown root:root "$tmp"; } && mv -Tf "$tmp" "$dest"; }; then
    rm -f "$tmp"
    return 1
  fi
  return 10
}

# strih_egress_pacing_install -> setup-strih step 11b. `none`: remove OUR script + unit (a live tree stays
# until the next boot, named). A rate: write the script + unit when they differ, daemon-reload, enable, and
# run the unit (the same idempotent `replace` script) only when a file changed or the live tree is not the
# declared one. rc 1 + a named reason on any failure.
strih_egress_pacing_install() {
  local rate nic script unit stext utext rc changed=0 queues verdict
  rate="$(strih_egress_pacing_rate)" || { echo "strih-egress-pacing: the box fact STRIH_EGRESS_PACING_RATE cannot be read" >&2; return 1; }
  script="$(strih_egress_pacing_script_path)"; unit="$(strih_egress_pacing_unit_path)"
  if [ "$rate" = none ]; then
    if [ -e "$unit" ] || { [ -f "$script" ] && grep -qF "$STRIH_EGRESS_PACING_MARKER" "$script" 2>/dev/null; }; then
      systemctl disable "${STRIH_EGRESS_PACING_SERVICE}.service" >/dev/null 2>&1 || true
      rm -f "$unit" "$script" || { echo "strih-egress-pacing: could not remove ${unit} / ${script}" >&2; return 1; }
      systemctl daemon-reload 2>/dev/null || true
      echo "  egress pacing: STRIH_EGRESS_PACING_RATE none -- removed ${STRIH_EGRESS_PACING_SERVICE} (a live tree stays until the next boot; now: tc qdisc del dev <rig nic> root)"
    else
      echo "  SKIP egress pacing: STRIH_EGRESS_PACING_RATE none (issue 1553)"
    fi
    return 0
  fi
  nic="$(strih_egress_pacing_nic)" || { echo "strih-egress-pacing: cannot resolve the rig NIC (above) -- set STRIH_NIC_IFACE" >&2; return 1; }
  stext="$(strih_egress_pacing_script_text "$nic" "$rate")" || { echo "strih-egress-pacing: cannot render the boot script for '${nic}' / '${rate}'" >&2; return 1; }
  utext="$(strih_egress_pacing_unit_text)"
  rc=0; _strih_egress_pacing_put "$script" 0755 "$stext" || rc=$?
  case "$rc" in 0) ;; 10) changed=1; echo "  egress pacing: ${script} written (dev ${nic}, fq maxrate ${rate})" ;; *) echo "strih-egress-pacing: could not write ${script}" >&2; return 1 ;; esac
  rc=0; _strih_egress_pacing_put "$unit" 0644 "$utext" || rc=$?
  case "$rc" in 0) ;; 10) changed=1; echo "  egress pacing: ${unit} written" ;; *) echo "strih-egress-pacing: could not write ${unit}" >&2; return 1 ;; esac
  if [ "$changed" = 1 ]; then systemctl daemon-reload || { echo "strih-egress-pacing: systemctl daemon-reload failed" >&2; return 1; }; fi
  if ! systemctl is-enabled -q "${STRIH_EGRESS_PACING_SERVICE}.service" 2>/dev/null; then
    systemctl enable "${STRIH_EGRESS_PACING_SERVICE}.service" >/dev/null 2>&1 || { echo "strih-egress-pacing: systemctl enable failed" >&2; return 1; }
  fi
  queues="$(strih_egress_pacing_queues "${STRIH_EGRESS_PACING_SYS:-/sys}" "$nic")"
  [ "$queues" -ge 1 ] || queues=1
  verdict="$(strih_egress_pacing_tree_verdict "$rate" "$queues" "$(tc -j qdisc show dev "$nic" 2>/dev/null || true)")"
  if [ "$changed" = 1 ] || [ "${verdict%% *}" != OK ]; then
    systemctl restart "${STRIH_EGRESS_PACING_SERVICE}.service" \
      || { echo "strih-egress-pacing: the live apply failed -- journalctl -u ${STRIH_EGRESS_PACING_SERVICE}" >&2; return 1; }
    echo "  egress pacing: applied live on ${nic} (tc replace, idempotent) -- was: ${verdict}"
  else
    echo "  egress pacing: ${nic} already paced (${verdict#OK }), unit enabled"
  fi
  return 0
}

# strih_egress_pacing_grade_report -> verify-strih item 16's rows through the caller's ok / bad / note:
# (egress-pacing-install) the installed script + unit = their render, enabled; (egress-pacing) the live
# tree (`tc -j qdisc show`). `none` = one NOTE, our leftover files = FAIL. Always returns 0.
strih_egress_pacing_grade_report() {
  local rate nic script unit stext state verdict queues fix
  rate="$(strih_egress_pacing_rate)" || { bad "(egress-pacing) the box fact STRIH_EGRESS_PACING_RATE cannot be read"; return 0; }
  script="$(strih_egress_pacing_script_path)"; unit="$(strih_egress_pacing_unit_path)"
  if [ "$rate" = none ]; then
    if [ -e "$unit" ] || [ -e "$script" ]; then
      bad "(egress-pacing) STRIH_EGRESS_PACING_RATE none but ${STRIH_EGRESS_PACING_SERVICE} is installed -- re-run setup-strih.sh step 11b"
    else
      note "(egress-pacing) STRIH_EGRESS_PACING_RATE none: the rig NIC egress is not paced (issue 1553)"
    fi
    return 0
  fi
  if ! nic="$(strih_egress_pacing_nic 2>/dev/null)"; then
    bad "(egress-pacing) cannot resolve the rig NIC (set STRIH_NIC_IFACE)"; return 0
  fi
  stext="$(strih_egress_pacing_script_text "$nic" "$rate")" || { bad "(egress-pacing) cannot render the boot script for '${nic}' / '${rate}'"; return 0; }
  state="$(systemctl is-enabled "${STRIH_EGRESS_PACING_SERVICE}.service" 2>/dev/null || true)"
  if [ ! -x "$script" ] || ! cmp -s "$script" <(printf '%s\n' "$stext"); then
    bad "(egress-pacing-install) ${script} is missing or not the render for dev ${nic} maxrate ${rate} -- re-run setup-strih.sh step 11b"
  elif ! cmp -s "$unit" <(strih_egress_pacing_unit_text); then
    bad "(egress-pacing-install) ${unit} is missing or not the render -- re-run setup-strih.sh step 11b"
  elif [ "${state%%$'\n'*}" != enabled ]; then
    bad "(egress-pacing-install) ${STRIH_EGRESS_PACING_SERVICE}.service is '${state:-unread}', not enabled -- the pacing is lost at the next boot; re-run setup-strih.sh step 11b"
  else
    ok "(egress-pacing-install) ${STRIH_EGRESS_PACING_SERVICE} installed + enabled (dev ${nic}, maxrate ${rate})"
  fi
  queues="$(strih_egress_pacing_queues "${STRIH_EGRESS_PACING_SYS:-/sys}" "$nic")"
  [ "$queues" -ge 1 ] || queues=1
  verdict="$(strih_egress_pacing_tree_verdict "$rate" "$queues" "$(tc -j qdisc show dev "$nic" 2>/dev/null || true)")"
  case "$verdict" in
    OK\ *) ok "(egress-pacing) ${nic} ${verdict#OK }" ;;
    *) fix="systemctl restart ${STRIH_EGRESS_PACING_SERVICE} (then journalctl -u ${STRIH_EGRESS_PACING_SERVICE})"
       bad "(egress-pacing) ${nic}: ${verdict#* } -- fix: ${fix}" ;;
  esac
  return 0
}
