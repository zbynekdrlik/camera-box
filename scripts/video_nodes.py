#!/usr/bin/env python3
"""Issue 1540 slice 3 -- the generator of the video node list dcontroller reads (venue -> nodes).

dcontroller (the Dante controller on the venue PCs) reads `GET http://<venue strih box>:8899/
video-nodes.json` and then one GET per node. The nodes are declared ONLY in this repo:

  * scripts/strih-boxes/<box>.env -- every Linux OBS box: STRIH_HOSTNAME, STRIH_IP (its venue-LAN
    address), STRIH_VENUE, STRIH_ROLE and the cameras its venue has (STRIH_CAMERAS);
  * scripts/camera-set.sh camera_resolve -- each camera's venue-LAN IP (the PP cameras are NATed to
    10.76.9.x for dev1 only; the venue LAN keeps the camera_resolve address);
  * scripts/lib/obs-fleet.sh OBS_FLEET -- which OBS box is current (a retired row is never listed).

The OBS box runs a FLAT /opt/camera-box tree that has none of those files, so this dev-side script
GENERATES the pure-data module scripts/bundle_state_video_nodes.py (deployed with the server, in
scripts/lib/bundle-state-files.{sh,txt}); tests/python/test_video_nodes_1540.py pins the committed
module equal to a fresh generation, so a moved fact fails the PR until it is regenerated.

The Windows OBS boxes (resolume-*, grading-pp) are not listed: OBS_FLEET carries no venue for them
and only a dev1-side or DNS address, never a venue-LAN fact.

CLI:
  video_nodes.py print           the venues dict as JSON
  video_nodes.py --write         rewrite scripts/bundle_state_video_nodes.py
  video_nodes.py --check         exit 1 when the committed module differs from a fresh generation
"""
from __future__ import annotations

import argparse
import importlib.util
import json
import os
import pprint
import re
import sys
from pathlib import Path

_SCRIPTS = Path(__file__).resolve().parent
MODULE_PATH = _SCRIPTS / "bundle_state_video_nodes.py"
CAMERA_SET_SH = _SCRIPTS / "camera-set.sh"
OBS_PORT = 8899
CAMBOX_PORT = 8896
_CAM_ARM = re.compile(r"^\s*(cam[0-9]+)\)\s*CAMERA_IP=([0-9.]+);", re.MULTILINE)
_CAM_NUM = re.compile(r"[0123456789]+")

_HEADER = '''"""GENERATED by scripts/video_nodes.py -- do not edit (issue 1540 slice 3).

The video node list per venue, from scripts/strih-boxes/*.env + scripts/camera-set.sh +
scripts/lib/obs-fleet.sh. Regenerate with `python3 scripts/video_nodes.py --write`;
tests/python/test_video_nodes_1540.py fails while this file differs from a fresh generation.
"""

'''


def _load(name):
    spec = importlib.util.spec_from_file_location(name, _SCRIPTS / f"{name}.py")
    mod = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(mod)
    return mod


def _strih_boxes_dir() -> Path:
    return Path(os.environ.get("VIDEO_NODES_STRIH_BOXES_DIR") or (_SCRIPTS / "strih-boxes"))


def _camera_ips() -> dict:
    return dict(_CAM_ARM.findall(CAMERA_SET_SH.read_text()))


def build() -> dict:
    """{venue: [node, ...]}: per venue its OBS boxes (by role, then name), then its cameras by
    number. Raises RuntimeError on a box absent from / retired in OBS_FLEET, a camera listed twice
    or unknown to camera_resolve, or a fact file without a venue / IP."""
    fact_file = _load("dantesync_fleet").fact_file
    fleet = {r[0]: r for r in _load("obs_fleet_table").fleet_rows()}
    cam_ips = _camera_ips()
    venues, seen_cams = {}, {}
    for f in sorted(_strih_boxes_dir().glob("*.env")):
        facts = fact_file(f)
        name, ip, venue = facts.get("STRIH_HOSTNAME", ""), facts.get("STRIH_IP", ""), facts.get("STRIH_VENUE", "")
        if not (name and ip and venue):
            raise RuntimeError(f"video_nodes: {f.name} lacks STRIH_HOSTNAME / STRIH_IP / STRIH_VENUE")
        row = fleet.get(name)
        if row is None:
            raise RuntimeError(f"video_nodes: {f.name} names {name!r}, which is no OBS_FLEET row")
        if row[3] == "retired":
            raise RuntimeError(f"video_nodes: {f.name} names {name!r}, retired in OBS_FLEET")
        nodes = venues.setdefault(venue, {"obs": [], "cambox": []})
        nodes["obs"].append({"name": name, "kind": "obs", "role": facts.get("STRIH_ROLE", ""),
                             "url": f"http://{ip}:{OBS_PORT}/video-connections.json"})
        cams = facts.get("STRIH_CAMERAS", "")
        for n in ([] if cams in ("", "none") else cams.split()):
            if not _CAM_NUM.fullmatch(n):
                raise RuntimeError(f"video_nodes: {f.name} lists camera {n!r}, not a camera number")
            cam = f"cam{int(n)}"
            if cam in seen_cams:
                raise RuntimeError(f"video_nodes: {cam} is listed by {seen_cams[cam]} and {f.name}")
            if cam not in cam_ips:
                raise RuntimeError(f"video_nodes: {f.name} lists {cam}, unknown to camera_resolve")
            seen_cams[cam] = f.name
            nodes["cambox"].append({"name": cam, "kind": "cambox",
                                    "url": f"http://{cam_ips[cam]}:{CAMBOX_PORT}/video.json"})
    out = {}
    for venue in sorted(venues):
        obs = sorted(venues[venue]["obs"], key=lambda n: (n["role"] != "strih", n["name"]))
        cams = sorted(venues[venue]["cambox"], key=lambda n: int(n["name"][3:]))
        out[venue] = obs + cams
    return out


def render(venues: dict) -> str:
    return _HEADER + "VENUES = " + pprint.pformat(venues, width=100, sort_dicts=False) + "\n"


def main(argv=None) -> int:
    ap = argparse.ArgumentParser(description="the issue-1540 video node list generator")
    ap.add_argument("cmd", nargs="?", choices=["print"])
    ap.add_argument("--write", action="store_true")
    ap.add_argument("--check", action="store_true")
    args = ap.parse_args(argv)
    text = render(build())
    if args.write:
        MODULE_PATH.write_text(text)
        print(f"video_nodes: wrote {MODULE_PATH}")
        return 0
    if args.check:
        current = MODULE_PATH.read_text() if MODULE_PATH.is_file() else ""
        if current != text:
            print(f"video_nodes: {MODULE_PATH.name} is stale -- run scripts/video_nodes.py --write",
                  file=sys.stderr)
            return 1
        print("video_nodes: up to date")
        return 0
    print(json.dumps(build(), indent=2))
    return 0


if __name__ == "__main__":
    sys.exit(main())
